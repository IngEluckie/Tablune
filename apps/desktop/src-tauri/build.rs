fn ensure_placeholder_icon(path: &str, contents: &[u8]) {
    let icon_path = Path::new(path);
    if icon_path.exists() {
        return;
    }

    fs::create_dir_all(icon_path.parent().expect("icon path must have a parent"))
        .expect("failed to create the Tauri icon directory");
    fs::write(icon_path, contents).expect("failed to write a temporary Tablune icon");
}
